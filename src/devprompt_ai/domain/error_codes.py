#: 全部已登记错误码（升序），供 M-10 静态检查遍历比对
ALL_ERROR_CODES: Final[tuple[int, ...]] = tuple(sorted(ERROR_CODES))

#: 5xxx：LLM 调用失败细分（Batch 1 新增，用户 2026-10-16 裁定）
#:
#: 与 3xxx 的 3004 语义区分——两者同源于供应商限流，但发生阶段不同：
#: 3004 = 决策阶段（排序/打分调用），5012 = 生成阶段（三套方案生成调用）。
#: 上层可据此告知用户「哪个环节被限流」。不要合并。
LLM_FAILURE_CODES: Final[dict[int, str]] = {
    code: meaning for code, meaning in ERROR_CODES.items() if 5010 < code < 5020
}
#: 5011–5019 是 **LLM 调用**失败（用户 2026-10-16 裁定 5 个码）；5021 起属其它外部依赖
#: （如模型目录拉取），刻意放在区间外，免得被这个范围推导误并入 LLM 失败集合。


def registered(code: int) -> int:
    """校验该码已在 :data:`ERROR_CODES` 登记并原样返回。

    供异常类的默认 code 使用：模块导入时即校验，**用错码会在导入期炸**，
    而不是等到线上返回给用户一个前端不认识的码（M-10 的前端映射表依赖码集完整）。
    """
    if code not in ERROR_CODES:
        raise KeyError(f"错误码 {code} 未在 error_codes.ERROR_CODES 中登记")
    return code
